    private void btnDeleteProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteProductActionPerformed
        // TODO add your handling code here:
        Object selectedProductObject = (Object)lstProducts.getSelectedValue();
        Product selectedProduct = (Product)selectedProductObject;
        
        DBManager db = new DBManager();
        db.deleteProduct(selectedProduct.getProductId());
        
        lblConfirmation.setText("Product removed");
        
        // instead of creating a new DefaultListModel, we use the currently existing one
        // we could use a new name instead of animalsModel but we can still use this while we're here
        DefaultListModel animalsModel = (DefaultListModel)lstProducts.getModel();
        animalsModel.remove(lstProducts.getSelectedIndex());
        // this will get the number of whatever has been selected, then delete that.
        lstProducts.setModel(animalsModel);
        
//        we still need to delete the animal from the hashmap though, rather than just the listbox.
        allProducts.remove(selectedProduct);
        
    }//GEN-LAST:event_btnDeleteProductActionPerformed

