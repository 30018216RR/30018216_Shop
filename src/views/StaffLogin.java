    private void btnStaffLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnStaffLoginActionPerformed
        String username = txtStaffUsername.getText();
        String password = txtStaffPassword.getText();
        
        DBManager db = new DBManager();
        Staff loggedInStaff = db.staffLogin(username, password);
        
        // if input not null, go to StaffHome
        if(loggedInStaff != null){
            StaffHome staffHome = new StaffHome(loggedInStaff); //this will present an error if we don't pass in loggedInPetrolCar, if trying to display the car logged in on PetrolHome.
            // load up new frame
            staffHome.setVisible(true);
            // hide this one
            this.setVisible(false);
        }
    }//GEN-LAST:event_btnStaffLoginActionPerformed

