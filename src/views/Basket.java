        public Basket(Order o) {
        // Initialising currentOrder
        currentOrder = o;
        initComponents();
        
        DefaultTableModel productBasketModel = (DefaultTableModel)tblProductBasket.getModel();

        for(Map.Entry<Integer,OrderLine> olMapEntry : o.getOrderLines().entrySet())
        {
            OrderLine ol = olMapEntry.getValue();
            
            productBasketModel.addRow(new Object[] {
                ol.getProductBought().getProductId(),
                //ol.getAnimalBought() //This would display .toString()
                ol.getProductBought().getProductName() + " - " + ol.getProductBought().getProductType(), "£" + ol.getProductBought().getPrice(),
                // "£" + ol.getLineTotal(),
                ol.getProductBought().getStockLevel()
                //Create getLineTotal() in OrderLine
            });
        }
 
    }

