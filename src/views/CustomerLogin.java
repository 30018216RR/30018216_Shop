    private void btnCustomerLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCustomerLoginActionPerformed
        // TODO add your handling code here:
        
    // creating variable for the text field
        String username = txtCustomerUsername.getText();
        String password = txtCustomerPassword.getText();
        
        // need to import things from models package into views package using Fix Imports.
        DBManager db = new DBManager();
        Customer loggedInCustomer = db.customerLogin(username, password);
        
        // if input not null, go to CustomerHome
        if(loggedInCustomer != null){
            CustomerHome customerHome = new CustomerHome(loggedInCustomer); //this will present an error if we don't pass in loggedInPetrolCar, if trying to display the car logged in on PetrolHome.
            // load up new frame
            customerHome.setVisible(true);
            // hide this one
            this.setVisible(false);
        }
    }//GEN-LAST:event_btnCustomerLoginActionPerformed

