    private void lstCategoriesValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_lstCategoriesValueChanged

        String productCategorySelected = lstCategories.getSelectedValue();

        // because the list uses a model (default values on the element), we need to create models for the for loop to search through.
        DefaultListModel lstProductsModel = new DefaultListModel();
        // this empties out the list so we can add our own values.

        // now we should loop through allAnimals (loaded at the start) and only get them if they are the selected category.
        for(Product product : allProducts){
            if(product.getClass().getName().equals("models." + productCategorySelected)){
                // this gets the class' name and returns a string - because of this, we need to use .equals()
                // now we need to add the entire Product object to the list.
                lstProductsModel.addElement(product);
            }
        }
        lstProducts.setModel(lstProductsModel);
    }//GEN-LAST:event_lstCategoriesValueChanged

