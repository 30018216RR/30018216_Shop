    private void btnAddProductActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddProductActionPerformed

    if(lstProducts.getSelectedIndex() != -1){
            Object selectedProductObject = (Object)lstProducts.getSelectedValue();
            // this needs to be converted to an Animal
            Product selectedProduct = (Product)selectedProductObject;
            //datatype first, then what we want to convert.


                OrderLine ol = new OrderLine(selectedProduct);
                // selectedAnimal is the constructor (from OrderLine) that we have to use here.
                currentOrder.addOrderLine(ol);
                lblOutputMessage.setText("Product added to basket.");
            }   
        else{
            lblOutputMessage.setText("Error: select product first");
        }
    
    }//GEN-LAST:event_btnAddProductActionPerformed

